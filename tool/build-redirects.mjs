#!/usr/bin/env node
// Compiles the redirect ledger into a module the Pages middleware imports.
//
// Cloudflare does not apply `public/_redirects` to requests handled by a Pages
// Function, and this site has a catch-all `functions/_middleware.js`. So every
// content redirect must run inside that Function. This turns the reviewable JSON
// ledger (src/content/_data/redirects.json) into a deterministic lookup table at
// functions/_generated/redirects.js, validating it on the way:
//
//   - sources and targets are site-absolute paths ("/…") — no open redirects;
//   - no duplicate source, no source that is also a target of another rule
//     without being collapsed (chains are resolved to their final target);
//   - no cycles;
//   - paths are normalized to a single trailing-slash form and stored decoded,
//     so an encoded Persian URL and its visible form resolve to one rule.
//
// Run with `--check` in CI to fail when the committed module is stale.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ledgerPath = resolve(root, 'src/content/_data/redirects.json');
const outPath = resolve(root, 'functions/_generated/redirects.js');
const check = process.argv.includes('--check');

const fail = (message) => {
  console.error(`build-redirects: ${message}`);
  process.exit(1);
};

/** One canonical path form: decoded, lower-cased host-agnostic, single trailing slash. */
function normalize(path) {
  if (typeof path !== 'string' || !path.startsWith('/')) {
    fail(`path must be a site-absolute string starting with "/": ${JSON.stringify(path)}`);
  }
  let clean = path.split('#')[0].split('?')[0];
  try {
    clean = decodeURIComponent(clean);
  } catch {
    fail(`path is not valid percent-encoding: ${path}`);
  }
  if (clean !== '/' && !clean.endsWith('/')) clean += '/';
  return clean;
}

const ledger = JSON.parse(await readFile(ledgerPath, 'utf8'));
const entries = Array.isArray(ledger.redirects) ? ledger.redirects : [];

const rules = new Map(); // normalized from → { to, code }
for (const entry of entries) {
  const from = normalize(entry.from);
  const to = normalize(entry.to);
  const code = entry.code ?? 301;
  if (![301, 302, 307, 308].includes(code)) fail(`unsupported status ${code} for ${entry.from}`);
  if (from === to) fail(`redirect points to itself: ${from}`);
  if (rules.has(from)) fail(`duplicate redirect source: ${from}`);
  rules.set(from, { to, code });
}

// Collapse chains (A→B, B→C ⇒ A→C) and reject cycles.
for (const [from, rule] of rules) {
  const seen = new Set([from]);
  let target = rule.to;
  while (rules.has(target)) {
    if (seen.has(target)) fail(`redirect cycle through ${target}`);
    seen.add(target);
    target = rules.get(target).to;
  }
  rule.to = target;
}

const sorted = [...rules.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const table = Object.fromEntries(sorted);

const module = `// GENERATED by tool/build-redirects.mjs from src/content/_data/redirects.json.
// Do not edit by hand — edit the ledger and run \`npm run build:redirects\`.
export const version = ${JSON.stringify(ledger.version ?? 1)};
export const redirects = ${JSON.stringify(table, null, 2)};
`;

if (check) {
  let current = '';
  try {
    current = await readFile(outPath, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== module) {
    fail('functions/_generated/redirects.js is stale — run `npm run build:redirects` and commit.');
  }
  console.log(`build-redirects: up to date (${sorted.length} rule(s))`);
} else {
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, module);
  console.log(`build-redirects: wrote ${sorted.length} rule(s), ${module.length} bytes`);
}
